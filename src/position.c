static const int knight_offsets[8][2]={{2,1},{2,-1},{-2,1},{-2,-1},{1,2},{1,-2},{-1,2},{-1,-2}};
static const int bishop_dirs[4][2]={{1,1},{1,-1},{-1,1},{-1,-1}};
static const int rook_dirs[4][2]={{1,0},{-1,0},{0,1},{0,-1}};

static u64 king_attacks[64];
static u64 knight_attacks[64];
static int tables_init=0;

static void init_tables(void){
    if(tables_init) return;
    for(int sq=0;sq<64;sq++){
        int r=sq/8,c=sq%8;
        u64 k=0,n=0;
        for(int i=0;i<8;i++){
            int nr=r+knight_offsets[i][0], nc=c+knight_offsets[i][1];
            if(nr>=0&&nr<8&&nc>=0&&nc<8) n |= 1ULL<<(nr*8+nc);
        }
        for(int dr=-1;dr<=1;dr++) for(int dc=-1;dc<=1;dc++){
            if(dr==0&&dc==0) continue;
            int nr=r+dr, nc=c+dc;
            if(nr>=0&&nr<8&&nc>=0&&nc<8) k |= 1ULL<<(nr*8+nc);
        }
        knight_attacks[sq]=n;
        king_attacks[sq]=k;
    }
    tables_init=1;
}

static u64 occupancy(const Position *p){
    u64 o=0;
    for(int i=0;i<12;i++) o|=p->bb[i];
    return o;
}

int piece_at(const Position *p,int sq){
    u64 b=1ULL<<sq;
    for(int i=0;i<12;i++) if(p->bb[i]&b) return i;
    return EMPTY;
}

u64 attacks_to(const Position *p,int sq,int side){
    /* attacks generated by side to square sq */
    u64 res=0;
    u64 occ=occupancy(p);
    if(side==0){ /* white attacks */
        /* pawns: from sq-7? white pawns attack up; squares that can attack sq are sq-7/sq-9 */
        if(sq>=9 && (sq%8)!=0) res |= (1ULL<<(sq-9)) & p->bb[W_P]; // pawn below-left? careful
        /* Actually white pawn attacks squares sq-7 and sq-9 from piece perspective. Piece locations: sq+7? Let's compute standard: white pawn attacks from sq to sq+7/sq+9. Occupied attackers at sq-7, sq-9. */
    }
    /* Simpler: generate all attacks by side and test bit */
    /* Reimplement below generically */
    res=0;
    /* pawns */
    if(side==0){
        /* white pawn attacks upward; piece at (r-1,c-1) or (r-1,c+1) */
        int r=sq/8,c=sq%8;
        if(r>0){
            if(c>0) { int ps=sq-9; if((p->bb[W_P]>>(ps))&1ULL) res|=1ULL<<ps; }
            if(c<7) { int ps=sq-7; if((p->bb[W_P]>>(ps))&1ULL) res|=1ULL<<ps; }
        }
    } else {
        int r=sq/8,c=sq%8;
        if(r<7){
            if(c>0){ int ps=sq+7; if((p->bb[B_P]>>ps)&1ULL) res|=1ULL<<ps; }
            if(c<7){ int ps=sq+9; if((p->bb[B_P]>>ps)&1ULL) res|=1ULL<<ps; }
        }
    }
    /* knights */
    u64 ntable = knight_attacks[sq];
    if(side==0) res |= ntable & p->bb[W_N];
    else res |= ntable & p->bb[B_N];
    /* king */
    u64 ktable = king_attacks[sq];
    if(side==0) res |= ktable & p->bb[W_K];
    else res |= ktable & p->bb[B_K];
    /* bishops/queens */
    for(int d=0;d<4;d++){
        int r=sq/8,c=sq%8;
        int dr=bishop_dirs[d][0], dc=bishop_dirs[d][1];
        int rr=r+dr, cc=c+dc;
        while(rr>=0&&rr<8&&cc>=0&&cc<8){
            int s=rr*8+cc;
            u64 b=1ULL<<s;
            if(side==0){
                if(p->bb[W_B]&b || p->bb[W_Q]&b){ res|=b; break;}
                if(occ&b) break;
            } else {
                if(p->bb[B_B]&b || p->bb[B_Q]&b){ res|=b; break;}
                if(occ&b) break;
            }
            rr+=dr; cc+=dc;
        }
    }
    /* rooks/queens */
    for(int d=0;d<4;d++){
        int r=sq/8,c=sq%8;
        int dr=rook_dirs[d][0], dc=rook_dirs[d][1];
        int rr=r+dr, cc=c+dc;
        while(rr>=0&&rr<8&&cc>=0&&cc<8){
            int s=rr*8+cc;
            u64 b=1ULL<<s;
            if(side==0){
                if(p->bb[W_R]&b || p->bb[W_Q]&b){ res|=b; break;}
                if(occ&b) break;
            } else {
                if(p->bb[B_R]&b || p->bb[B_Q]&b){ res|=b; break;}
                if(occ&b) break;
            }
            rr+=dr; cc+=dc;
        }
    }
    return res;
}

int in_check(const Position *p,int side){
    init_tables();
    /* find king */
    int king_sq=-1;
    if(side==0){ u64 k=p->bb[W_K]; if(k) king_sq=ctz64(k); }
    else { u64 k=p->bb[B_K]; if(k) king_sq=ctz64(k); }
    if(king_sq<0) return 1; /* no king -> check/mate */
    int opp = side^1;
    return (attacks_to(p, king_sq, opp) != 0);
}

void pos_init(Position *p){
    memset(p,0,sizeof(*p));
    p->ep=-1;
    p->castling=15;
    p->halfmove=0;
    p->fullmove=1;
    /* standard */
    pos_from_fen(p,"rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1");
    init_tables();
    pos_history_reset(p);
}

static int parse_square(const char *s){ return (s[1]-'1')*8 + (s[0]-'a'); }

int pos_from_fen(Position *p, const char *fen){
    init_tables();
    memset(p->bb,0,sizeof(p->bb));
    p->side=0; p->castling=0; p->ep=-1; p->halfmove=0; p->fullmove=1;
    pos_history_reset(p);
    char buf[256];
    snprintf(buf,sizeof(buf),"%s",fen);
    /* parse board */
    char *tok=strtok(buf," ");
    if(!tok) return 0;
    int r=7,c=0;
    for(int i=0;tok[i]&&r>=0;i++){
        char ch=tok[i];
        if(ch=='/'){ r--; c=0; continue; }
        if(isdigit((unsigned char)ch)){ c+=ch-'0'; continue; }
        int piece=-1;
        switch(ch){
            case 'P': piece=W_P; break; case 'N': piece=W_N; break; case 'B': piece=W_B; break;
            case 'R': piece=W_R; break; case 'Q': piece=W_Q; break; case 'K': piece=W_K; break;
            case 'p': piece=B_P; break; case 'n': piece=B_N; break; case 'b': piece=B_B; break;
            case 'r': piece=B_R; break; case 'q': piece=B_Q; break; case 'k': piece=B_K; break;
        }
        if(piece>=0 && r>=0 && c<8){ p->bb[piece] |= 1ULL<<(r*8+c); c++; }
    }
    tok=strtok(NULL," ");
    if(tok && (tok[0]=='b'||tok[0]=='B')) p->side=1;
    tok=strtok(NULL," ");
    if(tok){
        if(strchr(tok,'K')) p->castling|=1;
        if(strchr(tok,'Q')) p->castling|=2;
        if(strchr(tok,'k')) p->castling|=4;
        if(strchr(tok,'q')) p->castling|=8;
    }
    tok=strtok(NULL," ");
    if(tok && tok[0]!='-'){
        p->ep=parse_square(tok);
    }
    tok=strtok(NULL," ");
    if(tok) p->halfmove=atoi(tok);
    tok=strtok(NULL," ");
    if(tok) p->fullmove=atoi(tok);
    return 1;
}

int pos_to_fen(const Position *p, char *buf, int bufsz){
    int idx=0;
    for(int r=7;r>=0;r--){
        int empty=0;
        for(int c=0;c<8;c++){
            int sq=r*8+c;
            int pc=piece_at(p,sq);
            if(pc==EMPTY){ empty++; continue; }
            if(empty){ if(idx<bufsz-10) idx+=sprintf(buf+idx,"%d",empty); empty=0; }
            char ch="?pnbrqkPNBRQK"[pc+1];
            /* map */
            const char *pieces="pnbrqkPNBRQK";
            ch=pieces[pc];
            if(idx<bufsz-2) buf[idx++]=ch;
        }
        if(empty){ if(idx<bufsz-10) idx+=sprintf(buf+idx,"%d",empty); }
        if(r>0 && idx<bufsz-1) buf[idx++]='/';
    }
    idx += snprintf(buf+idx, bufsz-idx, " %c ", p->side?'b':'w');
    char cstr[5]=""; int ci=0;
    if(p->castling&1) cstr[ci++]='K';
    if(p->castling&2) cstr[ci++]='Q';
    if(p->castling&4) cstr[ci++]='k';
    if(p->castling&8) cstr[ci++]='q';
    if(ci==0) cstr[ci++]='-';
    cstr[ci]=0;
    idx += snprintf(buf+idx, bufsz-idx, "%s ", cstr);
    if(p->ep>=0){
        char esq[3]; esq[0]='a'+p->ep%8; esq[1]='1'+p->ep/8; esq[2]=0;
        idx += snprintf(buf+idx, bufsz-idx, "%s ", esq);
    } else idx += snprintf(buf+idx, bufsz-idx, "- ");
    idx += snprintf(buf+idx, bufsz-idx, "%d %d", p->halfmove, p->fullmove);
    buf[idx]=0;
    return idx;
}

u64 pos_hash(const Position *p){
    /* simple hash combining bitboards and state */
    u64 h=0;
    for(int i=0;i<12;i++) h ^= (p->bb[i]*0x9e3779b97f4a7c15ULL) + i;
    h ^= (u64)p->side*0xC2B2AE3D27D4EB4FULL;
    h ^= (u64)p->castling*0x1505ULL;
    h ^= (u64)(p->ep+1)*0xABCD1234EF567890ULL;
    return h;
}

int pos_side(const Position *p){ return p->side; }

void pos_history_reset(Position *p){
    if(p->history){ free(p->history); p->history=NULL; }
    p->hist_cap=64; p->hist_len=0;
    p->history=calloc(p->hist_cap,sizeof(u64));
}

void pos_history_push(Position *p,u64 h){
    if(p->hist_len>=p->hist_cap){
        p->hist_cap*=2;
        p->history=realloc(p->history,p->hist_cap*sizeof(u64));
    }
    p->history[p->hist_len++]=h;
}

int pos_is_repetition(const Position *p){
    if(p->hist_len<3) return 0;
    u64 cur=pos_hash(p);
    int count=0;
    for(int i=0;i<p->hist_len;i++){
        if(p->history[i]==cur) count++;
    }
    return count>=2; /* current not pushed? convention: history contains previous; if 2 previous same => threefold */
}

/* make/unmake */
void pos_make_move(Position *p, const Move *m, Undo *u){
    u->pos=p;
    u->side_before=p->side;
    u->castling_before=p->castling;
    u->ep_before=p->ep;
    u->halfmove_before=p->halfmove;
    u->moved_piece = piece_at(p,m->from);
    u->from=m->from; u->to=m->to;
    u->captured=m->captured;
    /* remove piece from from */
    if(u->moved_piece>=0) p->bb[u->moved_piece] &= ~(1ULL<<m->from);
    /* capture */
    if(m->captured>=0){
        p->bb[m->captured] &= ~(1ULL<<m->to);
    }
    /* ep capture */
    if(m->ep){
        int cap_sq = (p->side==0)? m->to-8 : m->to+8;
        int cap_piece = (p->side==0)? B_P : W_P;
        p->bb[cap_piece] &= ~(1ULL<<cap_sq);
        u->captured = cap_piece;
    }
    /* promotion */
    int pc = u->moved_piece;
    if(m->promoted>=0){
        int newpiece = m->promoted + (p->side==0?0:6);
        p->bb[newpiece] |= 1ULL<<m->to;
    } else {
        if(pc>=0) p->bb[pc] |= 1ULL<<m->to;
    }
    /* castling rook */
    if(m->castle==1){
        if(p->side==0){ p->bb[W_R] &= ~(1ULL<<7); p->bb[W_R] |= 1ULL<<5; }
        else { p->bb[B_R] &= ~(1ULL<<63); p->bb[B_R] |= 1ULL<<61; }
    } else if(m->castle==2){
        if(p->side==0){ p->bb[W_R] &= ~(1ULL<<0); p->bb[W_R] |= 1ULL<<3; }
        else { p->bb[B_R] &= ~(1ULL<<56); p->bb[B_R] |= 1ULL<<59; }
    }
    /* castling rights update */
    /* if king moves remove both */
    if(pc==W_K||pc==B_K){
        if(p->side==0){ p->castling &= ~3; }
        else { p->castling &= ~12; }
    }
    /* if rook moves */
    if(m->from==7||m->to==7) p->castling &= ~1;
    if(m->from==0||m->to==0) p->castling &= ~2;
    if(m->from==63||m->to==63) p->castling &= ~4;
    if(m->from==56||m->to==56) p->castling &= ~8;
    /* ep square */
    p->ep=-1;
    if(pc%6==0){ /* pawn */
        int diff = m->to - m->from;
        if((p->side==0 && diff==16) || (p->side==1 && diff==-16)){
            p->ep = (m->from + m->to)/2;
        }
    }
    /* halfmove */
    if(pc%6==0 || m->captured>=0 || m->ep) p->halfmove=0;
    else p->halfmove++;
    /* side */
    p->side ^= 1;
    if(p->side==0) p->fullmove++;
}

void pos_unmake_move(Position *p, const Move *m, const Undo *u){
    /* restore simple: revert side, fullmove */
    p->side = u->side_before;
    p->castling = u->castling_before;
    p->ep = u->ep_before;
    p->halfmove = u->halfmove_before;
    if(p->side==0) p->fullmove--; /* approximate; okay for search? fullmove not critical */
    /* remove piece from to */
    int pc_moved = u->moved_piece;
    /* promoted */
    if(m->promoted>=0){
        int newpiece = m->promoted + (u->side_before==0?0:6);
        p->bb[newpiece] &= ~(1ULL<<m->to);
    } else {
        if(pc_moved>=0) p->bb[pc_moved] &= ~(1ULL<<m->to);
    }
    /* restore moved piece to from */
    if(pc_moved>=0) p->bb[pc_moved] |= 1ULL<<m->from;
    /* restore captured */
    if(u->captured>=0){
        if(m->ep){
            int cap_sq = (u->side_before==0)? m->to-8 : m->to+8;
            p->bb[u->captured] |= 1ULL<<cap_sq;
        } else {
            p->bb[u->captured] |= 1ULL<<m->to;
        }
    }
    /* castling rook revert */
    if(m->castle==1){
        if(u->side_before==0){ p->bb[W_R] |= 1ULL<<7; p->bb[W_R] &= ~(1ULL<<5); }
        else { p->bb[B_R] |= 1ULL<<63; p->bb[B_R] &= ~(1ULL<<61); }
    } else if(m->castle==2){
        if(u->side_before==0){ p->bb[W_R] |= 1ULL<<0; p->bb[W_R] &= ~(1ULL<<3); }
        else { p->bb[B_R] |= 1ULL<<56; p->bb[B_R] &= ~(1ULL<<59); }
    }
}

int is_insufficient_material(const Position *p){
    /* only kings, or king+bishop/knight vs king */
    /* count pieces */
    int minor=0;
    for(int i=0;i<12;i++){
        if(i==W_K||i==B_K) continue;
        if(i%6==0){ /* pawns */ if(p->bb[i]) return 0; }
        if(i%6==3||i%6==4){ /* rook/queen */ if(p->bb[i]) return 0; }
        if(i%6==1||i%6==2){ if(p->bb[i]) minor++; }
    }
    /* if any pawns/rooks/queens already returned 0 */
    /* minor count */
    /* distributed? approximate: if <=1 minor each? Simplify: if total minor<=1 and no pawns/rooks/queens */
    /* count occupied minor pieces */
    int cnt=0;
    for(int i=0;i<12;i++){
        if(i%6==1||i%6==2) cnt += popcount64(p->bb[i]);
    }
    if(cnt<=1) return 1;
    /* bishop vs bishop same color? not essential */
    return 0;
}